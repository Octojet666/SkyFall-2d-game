export const dropTable = (kind, playerLevel = 1) => {
  const def = ENEMY_KINDS[kind] || BOSS_KINDS[kind];
  if (!def) return [];
  const out = [];
  for (const [id, base] of def.drops) {
    let chance = base;
    if (playerLevel >= 8) chance = Math.min(0.9, chance + 0.15);
    out.push([id, chance]);
  }
  return out;
};
